/**
 * Get countries for a specific service
 */
export function getCountriesByService(serviceType: ServiceType): Country[] {
  switch (serviceType) {
    case ServiceType.US_ESTA:
      return VWP_COUNTRIES;
    case ServiceType.UK_ETA:
      return UK_ETA_COUNTRIES;
    case ServiceType.CANADA_ETA:
      return CANADA_ETA_COUNTRIES;
    case ServiceType.THAILAND_TDAC:
      return []; // TDAC applies to all non-Thai nationals — country pages can be added later
    default:
      return [];
  }
}

/**
 * Get country by slug for a specific service
 */
export function getCountryBySlug(
  slug: string,
  serviceType: ServiceType
): Country | undefined {
  const countries = getCountriesByService(serviceType);
  return countries.find((country) => country.slug === slug);
}

/**
 * Get all country slugs for a specific service (for static generation)
 */
export function getAllCountrySlugs(serviceType: ServiceType): string[] {
  const countries = getCountriesByService(serviceType);
  return countries.map((country) => country.slug);
}

/**
 * Get countries by region for a specific service
 */
export function getCountriesByRegion(
  region: Country["region"],
  serviceType: ServiceType
): Country[] {
  const countries = getCountriesByService(serviceType);
  return countries.filter((country) => country.region === region);
}

/**
 * Search countries by name for a specific service
 */
export function searchCountries(
  query: string,
  serviceType: ServiceType
): Country[] {
  const lowerQuery = query.toLowerCase();
  const countries = getCountriesByService(serviceType);
  return countries.filter(
    (country) =>
      country.name.toLowerCase().includes(lowerQuery) ||
      country.slug.toLowerCase().includes(lowerQuery)
  );
}
